async function handleMessage(api, event, text) {
    const msg = text.trim();
    if (!msg) return;

    if (msg.includes("تعلم:") || msg.includes("تعلم ")) {
        const learnedCount = learnMultiplePhrases(msg);
        if (learnedCount > 0) {
            return api.sendMessage(`يعطيك الصحة يا الغالي! حفظت ${learnedCount} رد جديد 🌸`, event.threadID, event.messageID);
        }
    }

    const botResponse = getFromMemoryOrDatabase(msg);

    if (!botResponse) return;

    api.sendMessage(botResponse, event.threadID, (err, info) => {
        if (!err && global.GoatBot?.onReply) {
            global.GoatBot.onReply.set(info.messageID, {
               commandName: "rein",
               type: "reply",
               messageID: info.messageID,
               author: event.senderID,
               text: botResponse
            });
        }
    }, event.messageID);
}

module.exports.onStart = async ({ api, event, args }) => {
    const msg = args.join(" ").trim();
    await handleMessage(api, event, msg || "صفا");
};

module.exports.onReply = async ({ api, event }) => {
    if (event.type !== "message_reply") return;
    await handleMessage(api, event, event.body || "");
};

module.exports.onChat = async ({ api, event }) => {
    const message = event.body?.trim() || "";

    if (message.startsWith("/") || message.startsWith(".")) return;

    await handleMessage(api, event, message);
};
