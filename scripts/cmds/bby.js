// دالة للتحقق مما إذا كانت الرسالة عبارة عن إيموجيات فقط
function isOnlyEmojis(str) {
    const simpleEmojiRegex = /^[\p{Extended_Pictographic}\s]+$/u;
    return simpleEmojiRegex.test(str);
}

// دالة البحث الثابتة حصراً في قاعدة البيانات
function getFromDatabase(text) {
    const cleanText = text.toLowerCase().trim();

    // 🛑 حظر الأرقام تماماً ومنع الرد عليها
    if (/^\d+$/.test(cleanText)) {
        return null;
    }

    const cleanQuery = cleanText.replace("رين", "").replace("rein", "").trim();

    // 1. مطابقة الإيموجيات فقط
    if (isOnlyEmojis(cleanText)) {
        return cleanText;
    }

    // 2. المطابقة المباشرة والصرامة في قاعدة البيانات الثابتة فقط
    if (database[cleanQuery]) {
        const responses = database[cleanQuery];
        return responses[Math.floor(Math.random() * responses.length)];
    }
    if (database[cleanText]) {
        const responses = database[cleanText];
        return responses[Math.floor(Math.random() * responses.length)];
    }

    // إذا لم يجد نصاً مطابقاً، يتجاهل الرسالة تماماً وبصمت
    return null;
}

